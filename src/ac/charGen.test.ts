import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { CHAR_GEN_FILE_ID, parseCharGen } from "./charGen";

const root = new URL("../__fixtures__/chargen/", import.meta.url);
const retail = readFileSync(new URL("0x0e000002.bin", root));

test("pinned retail portal files are complete and SHA-256 verified offline", () => {
  const manifest = JSON.parse(readFileSync(new URL("manifest.json", root), "utf8"));
  assert.equal(manifest.archive, "portal");
  assert.equal(retail.length, 69469);
  assert.equal(createHash("sha256").update(retail).digest("hex"),
    "ed740a346e00e505175fba0ace039019ff2c09888a627718b653b27c8807627f");
  for (const entry of manifest.files) {
    const bytes = readFileSync(new URL(entry.file, root));
    assert.equal(bytes.length, entry.bytes, entry.file);
    assert.equal(bytes.readUInt32LE(0), Number(entry.id), entry.file);
    assert.equal(createHash("sha256").update(bytes).digest("hex"), entry.sha256, entry.file);
  }
});

test("retail CharGen walks all 13 heritages / 26 sexes and retains real body styles", () => {
  const cg = parseCharGen(retail);
  assert.equal(cg.id, CHAR_GEN_FILE_ID);
  assert.deepEqual([...cg.heritageGroups.keys()], Array.from({ length: 13 }, (_, i) => i + 1));
  for (const group of cg.heritageGroups.values()) assert.deepEqual([...group.genders.keys()], [1, 2]);
  const human = cg.heritageGroups.get(1)!.genders.get(1)!;
  assert.equal(human.name, "Male");
  assert.equal(human.setupId, 0x02000001);
  assert.equal(human.scale, 100);
  assert.equal(human.skinPaletteSetId, 0x0f000013);
  assert.deepEqual([human.hairStyles.length, human.hairColors.length, human.eyeColors.length,
    human.eyes.length, human.noses.length, human.mouths.length], [51, 4, 8, 19, 20, 42]);
  assert.equal(human.hairStyles[0].bald, true);
  assert.deepEqual(human.hairStyles[0].objDesc.parts, [{ partIndex: 16, gfxObjId: 0x010047f6 }]);
  assert.equal(human.eyes[0].objDesc.textures[0].newTextureId, 0x0500110d);
  assert.equal(human.eyes[0].baldObjDesc.textures[0].newTextureId, 0x050010ff);
  assert.equal(cg.heritageGroups.get(2)!.name, "Gharu'ndim");
  const gear = cg.heritageGroups.get(6)!.genders.get(1)!;
  assert.equal(gear.name, "Male");
  assert.equal(gear.scale, 120);
  assert.equal(gear.setupId, 0x02001907);
  assert.equal(gear.hairStyles.length, 7);
  assert.equal(gear.hairStyles[1].objDesc.parts.length, 17);
  assert.equal(gear.hairStyles[1].objDesc.textures.length, 16);
  assert.equal(gear.hairStyles[1].objDesc.textures[0].newTextureId, 0x05002f86);
  assert.equal(cg.heritageGroups.get(12)!.genders.get(1)!.hairStyles[1].objDesc.parts.length, 25);
  const acid = cg.heritageGroups.get(13)!.genders.get(1)!;
  assert.equal(acid.hairStyles[1].objDesc.parts.length, 31);
  assert.equal(acid.hairStyles[1].objDesc.textures.length, 0);
  assert.notEqual(cg.heritageGroups.get(11)!.genders.get(1)!.hairStyles[0].alternateSetupId, 0);
});

test("CharGen parsing respects subarray offsets and does not mutate fixture bytes", () => {
  const bytes = Buffer.concat([Buffer.alloc(17, 0xff), retail, Buffer.alloc(9, 0xff)]);
  const before = Buffer.from(bytes);
  assert.deepEqual(parseCharGen(bytes.subarray(17, -9)), parseCharGen(retail));
  assert.deepEqual(bytes, before);
});

test("malformed retail prefixes, excessive counts/size and trailing bytes fail closed", () => {
  for (const n of [0, 1, 3, 4, 8, 9, 10, 18, 200, 2000, 10000, retail.length - 1])
    assert.throws(() => parseCharGen(retail.subarray(0, n)), /CharGen:/, `prefix ${n}`);
  const wrongId = Buffer.from(retail); wrongId[0] = 3;
  assert.throws(() => parseCharGen(wrongId), /invalid file id/);
  assert.throws(() => parseCharGen(Buffer.concat([retail, Buffer.from([0])])), /trailing/);
  assert.throws(() => parseCharGen(new Uint8Array(16 * 1024 * 1024 + 1)), /size bound/);
  const count = Buffer.from(retail); count.set([0xff, 0xff, 0xff, 0xff], 8);
  assert.throws(() => parseCharGen(count), /count .* exceeds bound/);
  const name = Buffer.from(retail); name.set([0xff, 0xff, 0xff, 0xff, 0x7f], 9);
  assert.throws(() => parseCharGen(name), /string length exceeds bound/);
});

// Only boundary-encoding tests use generated bytes. Main parser/resolver tests
// use the complete retail file, not a JSON transcription or invented race data.
function minimal(options: { countWidth?: 1 | 2 | 4; badMarker?: boolean; duplicate?: boolean; invalidUtf8?: boolean } = {}): Uint8Array {
  const bytes: number[] = [];
  const u8 = (v: number) => { bytes.push(v & 255); };
  const u16 = (v: number) => { u8(v); u8(v >>> 8); };
  const u32 = (v: number) => { u16(v); u16(v >>> 16); };
  const align = () => { while (bytes.length % 4) u8(0); };
  const name = () => { u8(0x80); u8(1); for (let i = 0; i < 128; i++) u8(options.invalidUtf8 && i === 0 ? 0xff : 65); }; // .NET 7-bit length
  const count = (n: number) => {
    if (options.countWidth === 4) { u8(0xc0); u8(0); u16(n); }
    else if (options.countWidth === 2) { u8(0x80); u8(n); }
    else u8(n);
  };
  const desc = () => {
    align(); u8(options.badMarker ? 0 : 0x11); u8(1); u8(1); u8(1);
    u16(0x8001); u16(0x2345); // extended palette base
    u16(7); u8(2); u8(0); // zero length = 256 blocks
    u8(16); u16(0x8001); u16(0x0001); u16(2); // extended old texture
    u8(16); u16(0x8002); u16(0x3456); // extended GfxObj
    align();
  };
  const group = () => {
    u32(1); name(); for (let i = 0; i < 5; i++) u32(0);
    for (let i = 0; i < 4; i++) count(0);
    u8(1); count(1); u32(1); name(); for (let i = 0; i < 9; i++) u32(0);
    desc();
    for (let i = 0; i < 11; i++) count(0);
  };
  u32(CHAR_GEN_FILE_ID); u32(0); count(0); u8(1); count(options.duplicate ? 2 : 1);
  group(); if (options.duplicate) group();
  return new Uint8Array(bytes);
}

test("distinct smart-count/.NET-string encodings, extended DIDs and palette zero-length decode", () => {
  for (const countWidth of [1, 2, 4] as const) {
    const cg = parseCharGen(minimal({ countWidth }));
    assert.equal(cg.heritageGroups.get(1)!.name, "A".repeat(128));
    assert.deepEqual(cg.heritageGroups.get(1)!.genders.get(1)!.baseObjDesc, {
      paletteBaseId: 0x04012345,
      parts: [{ partIndex: 16, gfxObjId: 0x01023456 }],
      textures: [{ partIndex: 16, oldTextureId: 0x05010001, newTextureId: 0x05000002 }],
      palettes: [{ paletteId: 0x04000007, offset: 2, length: 256 }],
    });
  }
  assert.throws(() => parseCharGen(minimal({ badMarker: true })), /ObjDesc marker/);
  assert.throws(() => parseCharGen(minimal({ duplicate: true })), /duplicate key/);
  assert.throws(() => parseCharGen(minimal({ invalidUtf8: true })), /encoded data was not valid/);
});
